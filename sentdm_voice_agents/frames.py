def decode(data: dict[str, Any]) -> Frame:
    """The frame a JSON object carries. Raises FrameError when it breaks the protocol."""
    if not isinstance(data, dict) or not isinstance(data.get("type"), str):
        raise FrameError("a frame is a JSON object with a string type")
    kind = data["type"]
    check = _CHECKS.get(kind)
    if check is None:
        session_id = data.get("session_id")
        return UnknownFrame(type=kind, session_id=session_id if isinstance(session_id, str) else None, data=data)
    check(data, kind)
    return _BUILDERS[kind](data)


# Attributes whose wire key is a Python keyword.
_WIRE = {"from_": "from"}


def _plain(value: Any) -> Any:
    if hasattr(value, "__dataclass_fields__"):
        return {_WIRE.get(f.name, f.name): _plain(getattr(value, f.name)) for f in _fields(value) if getattr(value, f.name) is not None}
    if isinstance(value, dict):
        return {k: _plain(v) for k, v in value.items()}
    if isinstance(value, list):
        return [_plain(v) for v in value]
    return value


def encode(frame: Frame) -> dict[str, Any]:
    """The JSON object to send for a frame, with type first. Raises FrameError when it breaks the protocol."""
    if isinstance(frame, UnknownFrame):
        return dict(frame.data)
    data = {"type": frame.TYPE, **_plain(frame)}
    _CHECKS[frame.TYPE](data, frame.TYPE)
    return data
