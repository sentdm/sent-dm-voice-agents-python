def _check_party(d: Any, path: str = "Party") -> None:
    if not isinstance(d, dict):
        raise FrameError(f"{path} must be an object")
    if "kind" not in d:
        raise FrameError(f"{path}.kind is required")
    if "kind" in d:
        if not (isinstance(d["kind"], str) and (d["kind"] in ("user", "number", "conference", "agent", "anonymous",) or re.fullmatch("^[a-z][a-z0-9_]*$", d["kind"]))):
            raise FrameError(f"{path + '.kind'} is not an allowed value")
    if "value" in d:
        if not isinstance(d["value"], str):
            raise FrameError(f"{path + '.value'} must be a string")
        if len(d["value"]) < 1:
            raise FrameError(f"{path + '.value'} is shorter than 1")
    if d.get("kind") == "anonymous":
        pass
    else:
        if not isinstance(d, dict):
            raise FrameError(f"{path} must be an object")
        if "value" not in d:
            raise FrameError(f"{path}.value is required")
    if d.get("kind") == "number":
        if not isinstance(d, dict):
            raise FrameError(f"{path} must be an object")
        if "value" in d:
            if not isinstance(d["value"], str):
                raise FrameError(f"{path + '.value'} must be a string")
            if not re.fullmatch("^\\+[1-9][0-9]{6,14}$", d["value"]):
                raise FrameError(f"{path + '.value'} does not match '^\\+[1-9][0-9]{6,14}$'")


